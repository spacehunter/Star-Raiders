export const GLYPH_ROWS = 7;
export const GLYPH_COLUMNS = 8;

/** Rows of a glyph (unknown characters draw as blank). */
export function glyph(ch: string): readonly number[] {
  return G[ch.toUpperCase()] ?? G[' '];
}

/**
 * Draw `text` with each glyph pixel as a `px`-sized square, top-left at (x, y), using
 * `plot(x, y, w, h)` so the caller decides how logical pixels map to the screen.
 */
export function drawText(
  plot: (x: number, y: number, w: number, h: number) => void,
  text: string,
  x: number,
  y: number,
  px: number
): void {
  for (let i = 0; i < text.length; i++) {
    const rows = glyph(text[i]);
    const gx = x + i * GLYPH_COLUMNS * px;
    for (let r = 0; r < GLYPH_ROWS; r++) {
      const bits = rows[r];
      if (!bits) continue;
      for (let c = 0; c < GLYPH_COLUMNS; c++) {
        if (bits & (0x80 >> c)) plot(gx + c * px, y + r * px, px, px);
      }
    }
  }
}

