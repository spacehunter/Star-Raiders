/** Draw panel text in the ROM character set (8 × 8 per character). Unknown characters are blank. */
export function drawPanelText(
  plot: (x: number, y: number, w: number, h: number) => void,
  text: string,
  x: number,
  y: number
): void {
  for (let i = 0; i < text.length; i++) {
    const rows = ROM_PANEL_FONT[text[i]] ?? ROM_PANEL_FONT[' '];
    for (let r = 0; r < 8; r++) {
      for (let c = 0; c < 8; c++) if (rows[r] & (0x80 >> c)) plot(x + i * 8 + c, y + r, 1, 1);
    }
  }
}
