/** Shapes drawn from PLSHAP2TAB (the ROM's PLAYER0..1); the others use PLSHAP1TAB. */
const TABLE2: ReadonlySet<ShapeType> = new Set<ShapeType>([
  SHAPE.FIGHTER,
  SHAPE.STARBASE_RIGHT,
  SHAPE.STARBASE_LEFT,
  SHAPE.CRUISER,
  SHAPE.BASESTAR,
]);

/** PLAYER objects 8192 KM or more away (in the view's direction) are not drawn (R step 15). */
export const SPRITE_MAX_DISTANCE = 0x2000;

/** Number of shape cells per shape type. */
export const SHAPE_CELLS = 8;

/**
 * The high byte of |z| in the view's direction (R: "EOR #$FF" in the Aft view): z ≥ 0 KM in
 * front, z < 0 behind. Returns 255 for an object on the wrong side.
 */
export function viewDistanceHi(zKm: number, view: SpaceView): number {
  const hi = Math.floor(zKm / 256) & 0xff;
  if (view === 'FRONT') return zKm >= 0 ? hi : 0xff;
  return zKm < 0 ? hi ^ 0xff : 0xff;
}

/** Range index 0..15 for a distance high byte (R step 15). */
export function rangeIndex(distanceHi: number): number {
  return Math.min(15, distanceHi);
}

/** The shape cell 0..7 for a range index: the closer, the larger. */
export function shapeCell(range: number): number {
  return Math.min(15, Math.max(0, range)) >> 1;
}

/** Rows of a shape cell, top first (one byte per scanline). */
export function shapeRows(type: ShapeType, cell: number): number[] {
  const table = TABLE2.has(type) ? PLSHAP2TAB : PLSHAP1TAB;
  const offset = PLSHAPOFFTAB[type][cell];
  const height = PLSHAPHEIGHTTAB[type][cell] + 1;
  return table.slice(offset, offset + height);
}

/** Colour byte of a PLAYER: hue by type, luminance by range (R step 15, before special effects). */
export function shapeColor(type: ShapeType, range: number): number {
  return (PLSHAPCOLORTAB[type] ^ PLSHAPBRITTAB[Math.min(15, Math.max(0, range))]) & 0xff;
}

/** A sprite placed on the playfield: left column, top in scanlines (half rows) from row 0. */
export interface SpritePlacement {
  type: ShapeType;
  range: number;
  cell: number;
  /** Playfield column of the leftmost bit. */
  col: number;
  /** Top row in scanlines from the playfield's top (2 per playfield row). */
  line: number;
  rows: number[];
}

/**
 * Where a PLAYER object is drawn in a view, or null when it is not on screen (R steps 12 and
 * 15; SCREENCOLUMN/SCREENROW place a PLAYER 3 PM pixels left of the projected column and with
 * its top one playfield row above the projected row).
 */
export function placeSprite(type: ShapeType, x: number, y: number, z: number, view: SpaceView): SpritePlacement | null {
  const hi = viewDistanceHi(z, view);
  if (hi >= SPRITE_MAX_DISTANCE >> 8) return null;
  const px = projectPoint(x, y, z, view);
  if (!px) return null;
  const range = rangeIndex(hi);
  const cell = shapeCell(range);
  return { type, range, cell, col: px.col - 3, line: 2 * (px.row - 1), rows: shapeRows(type, cell) };
}

/** R: PLSTARBAOFFTAB — the starbase wings sit 8 PM pixels left and right of the centre, 4 scanlines lower. */
export const STARBASE_WING_OFFSET = 8;
export const STARBASE_WING_DROP = 4;

/**
 * The three-part starbase (R step 15 "Combine PLAYER0..2 to starbase shape"): the centre
 * (PLAYER2) where it projects, the left and right wings (PLAYER1, PLAYER0) 8 PM pixels to either
 * side and 4 scanlines lower, all with the centre's range. Empty when the centre is not drawn.
 */
export function placeStarbase(x: number, y: number, z: number, view: SpaceView): SpritePlacement[] {
  const centre = placeSprite(SHAPE.STARBASE_CENTER, x, y, z, view);
  if (!centre) return [];
  const out = [centre];
  for (const [type, dx] of [[SHAPE.STARBASE_LEFT, -STARBASE_WING_OFFSET], [SHAPE.STARBASE_RIGHT, STARBASE_WING_OFFSET]] as const) {
    const rows = shapeRows(type, centre.cell);
    out.push({ type, range: centre.range, cell: centre.cell, col: centre.col + dx, line: centre.line + STARBASE_WING_DROP, rows });
  }
  return out;
}

/** Does any lit pixel of sprite a overlap one of sprite b (the Player/Missile collision registers)? */
export function spritesOverlap(a: SpritePlacement, b: SpritePlacement): boolean {
  const dx = b.col - a.col;
  if (Math.abs(dx) >= 8) return false;
  for (let i = 0; i < a.rows.length; i++) {
    const j = a.line + i - b.line;
    if (j < 0 || j >= b.rows.length) continue;
    // Bit 7 is the leftmost pixel: shift b right by dx to put both in a's frame.
    const bRow = dx >= 0 ? b.rows[j] >> dx : (b.rows[j] << -dx) & 0xff;
    if (a.rows[i] & bRow) return true;
  }
  return false;
}

