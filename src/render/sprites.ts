/**
 * The ROM's PLAYER sprites (MANUAL_SPEC §17.13, §18.3; R: PLSHAP1TAB L10023, PLSHAP2TAB L10230,
 * PLSHAPOFFTAB L11156, PLSHAPHEIGHTTAB L11168, PLSHAPCOLORTAB L11512, PLSHAPBRITTAB L11524,
 * PLSTARBAOFFTAB L11199, GAMELOOP step 15).
 *
 * Every space object that is a PLAYER (Zylon ships, torpedoes, meteor, starbase) is an 8-pixel
 * wide bitmap. Each shape type has 8 "shape cells", one per distance step: the high byte of |z|
 * (KM, in the view's direction), capped at 15, is the range index; the cell is range / 2. Objects
 * 8192 KM or more away are not drawn; cell 6 is the one-pixel Long-Range Scan dot.
 *
 * One sprite row is one scanline: half a playfield row (Player/Missile single-line resolution),
 * so each sprite pixel is twice as wide as it is tall.
 *
 * Bytes below are copied from the ROM; each byte is one row, bit 7 the leftmost pixel.
 */
import { CENTER_COL, CENTER_ROW, projectPoint, type SpaceView } from './projection';

